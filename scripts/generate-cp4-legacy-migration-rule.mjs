#!/usr/bin/env node
// Offline deterministic generator for the self-contained CP4 legacy
// migration-rule candidate. Generation does not activate or approve the rule.

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  LEGACY_MIGRATION_RULE_ARTIFACT,
  buildLegacyMigrationRule,
  loadAndValidateLegacyMigrationRule,
  serializeLegacyMigrationRule,
  validateLegacyMigrationRule
} from "../src/cp4-legacy-migration-rule.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

function sha256(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

function assertSafeOutputTarget(outputPath) {
  try {
    const stats = fs.lstatSync(outputPath);
    if (stats.isSymbolicLink()) {
      throw new Error("existing output target must not be a symlink");
    }
    if (!stats.isFile()) {
      throw new Error("existing output target must be a regular file");
    }
  } catch (error) {
    if (error?.code === "ENOENT") return;
    throw error;
  }
}

function writeRuleAtomically(repositoryRoot, bytes) {
  const rootRealPath = fs.realpathSync(repositoryRoot);
  if (!fs.statSync(rootRealPath).isDirectory()) {
    throw new Error("repositoryRoot must resolve to a directory");
  }
  const outputPath = path.join(rootRealPath, LEGACY_MIGRATION_RULE_ARTIFACT);
  assertSafeOutputTarget(outputPath);

  const temporaryPath = path.join(
    rootRealPath,
    `.${LEGACY_MIGRATION_RULE_ARTIFACT}.${process.pid}.${crypto.randomBytes(12).toString("hex")}.tmp`
  );
  let descriptor;
  try {
    if (!Number.isInteger(fs.constants.O_NOFOLLOW)) {
      throw new Error("this platform does not expose O_NOFOLLOW");
    }
    descriptor = fs.openSync(
      temporaryPath,
      fs.constants.O_CREAT
        | fs.constants.O_EXCL
        | fs.constants.O_WRONLY
        | fs.constants.O_NOFOLLOW,
      0o600
    );
    fs.writeFileSync(descriptor, bytes, "utf8");
    fs.fsyncSync(descriptor);
    fs.fchmodSync(descriptor, 0o644);
    fs.closeSync(descriptor);
    descriptor = undefined;

    // Recheck immediately before rename. rename replaces the directory entry
    // itself, so a hostile last-moment symlink cannot redirect the write.
    assertSafeOutputTarget(outputPath);
    fs.renameSync(temporaryPath, outputPath);
  } finally {
    if (descriptor !== undefined) fs.closeSync(descriptor);
    try {
      fs.unlinkSync(temporaryPath);
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
  }
}

/**
 * Build the deterministic CP4 legacy migration-rule candidate bytes.
 *
 * @param {string} [repositoryRoot] Absolute SteerBench repository root.
 * @returns {{rule: object, bytes: string, receipt: {artifact: string, sha256: string}}}
 *   Candidate, canonical raw bytes, and prospective raw-byte receipt.
 */
export function buildLegacyMigrationRuleArtifact(repositoryRoot = ROOT) {
  const rule = buildLegacyMigrationRule(repositoryRoot);
  const bytes = serializeLegacyMigrationRule(rule);
  validateLegacyMigrationRule(rule, { repositoryRoot, rawBytes: bytes });
  return {
    rule,
    bytes,
    receipt: {
      artifact: LEGACY_MIGRATION_RULE_ARTIFACT,
      sha256: sha256(Buffer.from(bytes, "utf8"))
    }
  };
}

/**
 * Write and re-read the deterministic CP4 legacy migration-rule candidate.
 *
 * @param {string} [repositoryRoot] Absolute SteerBench repository root.
 * @returns {{rule: object, bytes: string, receipt: {artifact: string, sha256: string}}}
 *   Written candidate, canonical bytes, and verified raw-byte receipt.
 */
export function generateLegacyMigrationRuleArtifact(repositoryRoot = ROOT) {
  const built = buildLegacyMigrationRuleArtifact(repositoryRoot);
  writeRuleAtomically(repositoryRoot, built.bytes);
  const loaded = loadAndValidateLegacyMigrationRule(repositoryRoot);
  if (loaded.receipt.sha256 !== built.receipt.sha256) {
    throw new Error("written legacy migration-rule bytes differ from generated bytes");
  }
  return { ...built, rule: loaded.rule, receipt: loaded.receipt };
}

const isMain = process.argv[1]
  && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isMain) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    console.error("usage: node scripts/generate-cp4-legacy-migration-rule.mjs [--check]");
    process.exitCode = 1;
  } else {
    const result = args[0] === "--check"
      ? loadAndValidateLegacyMigrationRule(ROOT)
      : generateLegacyMigrationRuleArtifact(ROOT);
    console.log(`${result.receipt.artifact} ${result.receipt.sha256}`);
  }
}
